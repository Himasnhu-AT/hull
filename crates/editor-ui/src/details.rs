//! Details: one collapsible section per component of the first selected entity.

use ashlar_ui::tokens;
use editor_proto::{ComponentDoc, EntityId, Op, StableOrId, TypeSchema};
use egui::{RichText, Ui};

use crate::model::{NodeInfo, Req};
use crate::props::{self, Cx, Phase};

#[derive(Default)]
pub(crate) struct DetailsState {
    add_filter: String,
    /// Hides components whose name does not match.
    filter: String,
}

pub(crate) struct View<'a> {
    pub id: Option<EntityId>,
    pub info: Option<&'a NodeInfo>,
    pub extra_selected: usize,
    pub components: &'a Result<Vec<ComponentDoc>, String>,
    pub types: &'a [(String, TypeSchema)],
}

pub(crate) fn show(ui: &mut Ui, st: &mut DetailsState, v: &View<'_>, reqs: &mut Vec<Req>) {
    let t = tokens::current(ui.ctx());
    let (Some(id), Some(info)) = (v.id, v.info) else {
        ui.add_space(t.space.md);
        match v.id {
            Some(id) => ui.label(RichText::new(format!("Entity {id} is selected (not in the tree yet)")).color(t.text.disabled)),
            None => ui.label(RichText::new("Nothing selected").color(t.text.disabled)),
        };
        return;
    };
    let eref = info.reference;
    egui::ScrollArea::vertical().auto_shrink([false, false]).show(ui, |ui| {
        header(ui, id, info, v.extra_selected, reqs);
        ui.add_space(t.space.xs);
        ui.add(egui::TextEdit::singleline(&mut st.filter).hint_text("Search components").desired_width(f32::INFINITY));
        ui.add_space(t.space.xs);
        ui.separator();
        match v.components {
            Err(e) => {
                ui.colored_label(t.status.danger, e);
            }
            Ok(comps) => {
                let f = st.filter.to_lowercase();
                let shown: Vec<&ComponentDoc> = comps.iter().filter(|d| f.is_empty() || d.short_name.to_lowercase().contains(&f)).collect();
                if shown.is_empty() && !f.is_empty() {
                    ui.label(RichText::new("No component matches").color(t.text.disabled));
                }
                for doc in shown {
                    section(ui, id, eref, info.generated, doc, reqs);
                    ui.add_space(t.space.xs);
                }
                ui.add_space(t.space.md);
                if !info.generated {
                    add_component(ui, st, eref, comps, v.types, reqs);
                }
            }
        }
    });
}

fn header(ui: &mut Ui, id: EntityId, info: &NodeInfo, extra: usize, reqs: &mut Vec<Req>) {
    let t = tokens::current(ui.ctx());
    ui.horizontal(|ui| {
        let mut name = info.name.clone();
        let r = ui.add_enabled(
            !info.generated,
            egui::TextEdit::singleline(&mut name)
                .font(egui::TextStyle::Heading)
                .desired_width(ui.available_width() - 70.0),
        );
        if r.lost_focus() && name.trim() != info.name && !name.trim().is_empty() {
            reqs.push(Req::Edit {
                op: Op::Rename {
                    entity: info.reference,
                    before: info.name.clone(),
                    after: name.trim().to_owned(),
                },
                label: "Rename".into(),
                key: None,
                seal: true,
            });
        }
    });
    // What it is, and its id (the stable id when it has one: that is what the level file stores).
    let ident = match info.reference {
        StableOrId::Stable(s) => format!("id {}", s.0),
        StableOrId::Id(i) => format!("session id {i}"),
    };
    ui.horizontal(|ui| {
        ui.label(RichText::new(crate::outliner::kind_label(info.kind, info.generated)).color(t.accent).small());
        ui.label(RichText::new(ident).color(t.text.disabled).small());
    });
    if info.generated {
        generated_banner(ui, id, info, reqs);
    }
    if extra > 0 {
        ui.label(RichText::new(format!("+{extra} more selected (showing the first)")).color(t.text.secondary).small());
    }
}

/// "Generated by X", why it is read-only, and the way out.
fn generated_banner(ui: &mut Ui, id: EntityId, info: &NodeInfo, reqs: &mut Vec<Req>) {
    let t = tokens::current(ui.ctx());
    let title = match info.origin.as_deref() {
        Some(o) if o != "generated" => format!("Generated by {o}"),
        _ => "Generated by code".to_string(),
    };
    egui::Frame::new().fill(t.status.warning.gamma_multiply(0.14)).stroke(egui::Stroke::new(1.0, t.status.warning)).corner_radius(4.0).inner_margin(egui::Margin::same(6)).show(ui, |ui| {
        ui.label(RichText::new(title).strong().color(t.text.primary));
        ui.label(RichText::new("Read-only here: built by code, so the gizmo is off and edits are refused. Make it a level entity to move, edit and save it.").small().color(t.text.secondary));
        if ui.button("Convert to level entity").on_hover_text("Gives it a stable id and a name; undoable. Meshes that are not shapes are not written to the level file.").clicked() {
            reqs.push(Req::Convert(id));
        }
    });
}

fn section(ui: &mut Ui, id: EntityId, eref: StableOrId, generated: bool, doc: &ComponentDoc, reqs: &mut Vec<Req>) {
    let t = tokens::current(ui.ctx());
    let sid = ui.make_persistent_id(("details.section", &doc.type_path));
    let state = egui::collapsing_header::CollapsingState::load_with_default_open(ui.ctx(), sid, true);
    let editable = doc.editable && !generated;
    let mut remove = false;
    state
        .show_header(ui, |ui| {
            ui.label(RichText::new(&doc.short_name).strong().color(t.text.primary)).on_hover_text(&doc.type_path);
            if !doc.editable {
                ui.label(RichText::new("read-only").color(t.text.disabled).small());
            }
            if editable && props::right_button(ui, "x", "Remove component") {
                remove = true;
            }
        })
        .body(|ui| {
            let mut working = doc.value.clone();
            let mut cx = Cx::new(format!("{id}.{}", doc.type_path), !editable);
            props::component_body(ui, &mut cx, &doc.schema, &mut working);
            if let Some(change) = cx.change
                && change.phase != Phase::Begin
                && working != doc.value
            {
                reqs.push(Req::Edit {
                    op: Op::SetComponent {
                        entity: eref,
                        type_path: doc.type_path.clone(),
                        before: Some(doc.value.clone()),
                        after: Some(working),
                    },
                    label: format!("Edit {}", doc.short_name),
                    key: Some(format!("{id}|{}|{}", doc.type_path, change.path)),
                    seal: matches!(change.phase, Phase::Commit | Phase::Cancel),
                });
            }
        });
    if remove {
        reqs.push(Req::Edit {
            op: Op::SetComponent {
                entity: eref,
                type_path: doc.type_path.clone(),
                before: Some(doc.value.clone()),
                after: None,
            },
            label: format!("Remove {}", doc.short_name),
            key: None,
            seal: true,
        });
    }
}

fn add_component(ui: &mut Ui, st: &mut DetailsState, eref: StableOrId, have: &[ComponentDoc], types: &[(String, TypeSchema)], reqs: &mut Vec<Req>) {
    egui::ComboBox::from_id_salt("details.add_component")
        .selected_text("Add component")
        .width(ui.available_width() - 8.0)
        .show_ui(ui, |ui| {
            ui.add(egui::TextEdit::singleline(&mut st.add_filter).hint_text("Filter").desired_width(f32::INFINITY));
            let f = st.add_filter.to_lowercase();
            egui::ScrollArea::vertical().max_height(260.0).show(ui, |ui| {
                for (path, schema) in types {
                    if have.iter().any(|d| d.type_path == *path) {
                        continue;
                    }
                    let short = path.rsplit("::").next().unwrap_or(path);
                    if !f.is_empty() && !short.to_lowercase().contains(&f) {
                        continue;
                    }
                    if ui.selectable_label(false, short).on_hover_text(path).clicked() {
                        reqs.push(Req::Edit {
                            op: Op::SetComponent {
                                entity: eref,
                                type_path: path.clone(),
                                before: None,
                                after: Some(props::default_value(schema)),
                            },
                            label: format!("Add {short}"),
                            key: None,
                            seal: true,
                        });
                        st.add_filter.clear();
                        ui.close();
                    }
                }
            });
        });
}
