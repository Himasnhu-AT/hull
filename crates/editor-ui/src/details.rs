//! Details: one collapsible section per component of the first selected entity.

use ashlar_ui::tokens;
use editor_proto::{ComponentDoc, EntityId, Op, StableOrId, TypeSchema};
use egui::{RichText, Ui};

use crate::model::{NodeInfo, Req};
use crate::props::{self, Cx, Phase};

#[derive(Default)]
pub(crate) struct DetailsState {
    add_filter: String,
}

pub(crate) struct View<'a> {
    pub id: Option<EntityId>,
    pub info: Option<&'a NodeInfo>,
    pub extra_selected: usize,
    pub components: &'a Result<Vec<ComponentDoc>, String>,
    pub types: &'a [(String, TypeSchema)],
}

pub(crate) fn show(ui: &mut Ui, st: &mut DetailsState, v: &View<'_>, reqs: &mut Vec<Req>) {
    let t = tokens::current(ui.ctx());
    let (Some(id), Some(info)) = (v.id, v.info) else {
        ui.add_space(t.space.md);
        ui.label(RichText::new("Nothing selected").color(t.text.disabled));
        return;
    };
    let eref = info.reference;
    egui::ScrollArea::vertical().auto_shrink([false, false]).show(ui, |ui| {
        header(ui, id, info, v.extra_selected, reqs);
        ui.separator();
        match v.components {
            Err(e) => {
                ui.colored_label(t.status.danger, e);
            }
            Ok(comps) => {
                for doc in comps {
                    section(ui, id, eref, info.generated, doc, reqs);
                }
                ui.add_space(t.space.md);
                if !info.generated {
                    add_component(ui, st, eref, comps, v.types, reqs);
                }
            }
        }
    });
}

fn header(ui: &mut Ui, id: EntityId, info: &NodeInfo, extra: usize, reqs: &mut Vec<Req>) {
    let t = tokens::current(ui.ctx());
    ui.horizontal(|ui| {
        let mut name = info.name.clone();
        let r = ui.add_enabled(!info.generated, egui::TextEdit::singleline(&mut name).font(egui::TextStyle::Heading).desired_width(ui.available_width() - 70.0));
        if r.lost_focus() && name.trim() != info.name && !name.trim().is_empty() {
            reqs.push(Req::Edit { op: Op::Rename { entity: info.reference, before: info.name.clone(), after: name.trim().to_owned() }, label: "Rename".into(), key: None, seal: true });
        }
        ui.label(RichText::new(format!("#{id}")).color(t.text.disabled).small());
    });
    if info.generated {
        ui.label(RichText::new("Generated by code: read-only").color(t.text.secondary).small());
    }
    if extra > 0 {
        ui.label(RichText::new(format!("+{extra} more selected (showing the first)")).color(t.text.secondary).small());
    }
}

fn section(ui: &mut Ui, id: EntityId, eref: StableOrId, generated: bool, doc: &ComponentDoc, reqs: &mut Vec<Req>) {
    let t = tokens::current(ui.ctx());
    let sid = ui.make_persistent_id(("details.section", &doc.type_path));
    let state = egui::collapsing_header::CollapsingState::load_with_default_open(ui.ctx(), sid, true);
    let editable = doc.editable && !generated;
    let mut remove = false;
    state
        .show_header(ui, |ui| {
            ui.label(RichText::new(&doc.short_name).strong().color(t.text.primary)).on_hover_text(&doc.type_path);
            if !doc.editable {
                ui.label(RichText::new("read-only").color(t.text.disabled).small());
            }
            if editable && props::right_button(ui, "x", "Remove component") {
                remove = true;
            }
        })
        .body(|ui| {
            let mut working = doc.value.clone();
            let mut cx = Cx::new(format!("{id}.{}", doc.type_path), !editable);
            props::component_body(ui, &mut cx, &doc.schema, &mut working);
            if let Some(change) = cx.change
                && change.phase != Phase::Begin
                && working != doc.value
            {
                reqs.push(Req::Edit {
                    op: Op::SetComponent { entity: eref, type_path: doc.type_path.clone(), before: Some(doc.value.clone()), after: Some(working) },
                    label: format!("Edit {}", doc.short_name),
                    key: Some(format!("{id}|{}|{}", doc.type_path, change.path)),
                    seal: matches!(change.phase, Phase::Commit | Phase::Cancel),
                });
            }
        });
    if remove {
        reqs.push(Req::Edit {
            op: Op::SetComponent { entity: eref, type_path: doc.type_path.clone(), before: Some(doc.value.clone()), after: None },
            label: format!("Remove {}", doc.short_name),
            key: None,
            seal: true,
        });
    }
}

fn add_component(ui: &mut Ui, st: &mut DetailsState, eref: StableOrId, have: &[ComponentDoc], types: &[(String, TypeSchema)], reqs: &mut Vec<Req>) {
    egui::ComboBox::from_id_salt("details.add_component").selected_text("Add component").width(ui.available_width() - 8.0).show_ui(ui, |ui| {
        ui.add(egui::TextEdit::singleline(&mut st.add_filter).hint_text("Filter").desired_width(f32::INFINITY));
        let f = st.add_filter.to_lowercase();
        egui::ScrollArea::vertical().max_height(260.0).show(ui, |ui| {
            for (path, schema) in types {
                if have.iter().any(|d| d.type_path == *path) {
                    continue;
                }
                let short = path.rsplit("::").next().unwrap_or(path);
                if !f.is_empty() && !short.to_lowercase().contains(&f) {
                    continue;
                }
                if ui.selectable_label(false, short).on_hover_text(path).clicked() {
                    reqs.push(Req::Edit {
                        op: Op::SetComponent { entity: eref, type_path: path.clone(), before: None, after: Some(props::default_value(schema)) },
                        label: format!("Add {short}"),
                        key: None,
                        seal: true,
                    });
                    st.add_filter.clear();
                    ui.close();
                }
            }
        });
    });
}
