/// <reference types="node" />
// Maintainer script: builds crates/hull-kernels to WebAssembly and writes it, as base64 with the stamp of the source
// it came from, to packages/hull/src/kernel/wasm.ts. That file is committed, so only someone changing a kernel needs
// Rust (rustup target add wasm32-unknown-unknown); `pnpm check` fails when the stamp and the source disagree.
//   pnpm kernels:build
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { kernelSourceStamp } from '../packages/hull/src/kernel/stamp.ts';

const root = fileURLToPath(new URL('../', import.meta.url));
const crate = join(root, 'crates', 'hull-kernels');
// Run from the crate so its .cargo/config.toml (the small stack) applies.
execFileSync('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown', '--locked'], { cwd: crate, stdio: 'inherit' });
const wasm = readFileSync(join(root, 'target', 'wasm32-unknown-unknown', 'release', 'hull_kernels.wasm'));
const module = new WebAssembly.Module(wasm);
const imports = WebAssembly.Module.imports(module);
if (imports.length) throw new Error('the kernel module must import nothing, it imports: ' + imports.map((i) => i.module + '.' + i.name).join(', '));
const stamp = kernelSourceStamp(root);
const base64 = wasm.toString('base64');
const lines = base64.match(/.{1,116}/g) ?? [];
writeFileSync(join(root, 'packages', 'hull', 'src', 'kernel', 'wasm.ts'), [
  '// Generated by `pnpm kernels:build` from crates/hull-kernels. Do not edit: kernel.test.ts compares the stamp with the',
  '// source, so a change to the crate without a rebuild fails `pnpm check`.',
  '',
  '/** sha256 of the crate source this module was built from (kernel/stamp.ts). */',
  `export const KERNEL_STAMP = '${stamp}';`,
  '/** Size of the WebAssembly module in bytes. */',
  `export const KERNEL_BYTES = ${wasm.length};`,
  '/** The module, base64. */',
  'export const KERNEL_BASE64 =',
  lines.map((l) => `  '${l}'`).join(' +\n') + ';',
  '',
].join('\n'));
console.log(`kernel: ${wasm.length} bytes, exports ${WebAssembly.Module.exports(module).map((e) => e.name).join(' ')}; stamp ${stamp.slice(0, 12)}`);
